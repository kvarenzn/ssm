var invSBox = make([]byte, 256)

var rcon = []byte{0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36, 0x6c, 0xd8, 0xab, 0x4d, 0x9a}

var shifts = map[int][]byte{
	4: {0, 1, 2, 3},
	6: {0, 1, 2, 3},
	8: {0, 1, 3, 4},
}

func init() {
	for i, v := range sbox {
		invSBox[v] = byte(i)
	}
}

func mul(a, b byte) byte {
	r := byte(0)
	for b != 0 {
		if b&1 != 0 {
			r ^= a
		}
		if a&0x80 != 0 {
			a = (a << 1) ^ 0x1b
		} else {
			a <<= 1
		}
		b >>= 1
	}
	return r
}

func expand(key []byte, nBlocks int) ([][]byte, int) {
	nk := len(key) / 4
	nr := max(nk, nBlocks) + 6
	w := make([][]byte, nk)
	for i := range nk {
		w[i] = key[4*i : 4*i+4]
	}

	for i := nk; i < nBlocks*(nr+1); i++ {
		t := slices.Clone(w[i-1])
		if i%nk == 0 {
			t = slices.Concat(t[1:], t[:1])
			for i, b := range t {
				t[i] = sbox[b]
			}
			t[0] ^= rcon[i/nk-1]
		} else if nk > 6 && i%nk == 4 {
			for i, b := range t {
				t[i] = sbox[b]
			}
		}

		n := make([]byte, 4)
		for j := range 4 {
			n[j] = w[i-nk][j] ^ t[j]
		}
		w = append(w, n)
	}

	return w, nr
}

func decodeBlock(blk []byte, w [][]byte, nr int, nBlocks int) []byte {
	sh := shifts[nBlocks]
	st := slices.Clone(blk)

	addrk := func(rnd int) {
		for c := range nBlocks {
			for r := range 4 {
				st[4*c+r] ^= w[rnd*nBlocks+c][r]
			}
		}
	}

	invShift := func() {
		for r := 1; r < 4; r++ {
			s := sh[r]
			if s == 0 {
				continue
			}

			row := make([]byte, nBlocks)
			for c := range nBlocks {
				row[c] = st[4*c+r]
			}
			cp := len(row) - int(s)
			row = slices.Concat(row[cp:], row[:cp])
			for c := range nBlocks {
				st[4*c+r] = row[c]
			}
		}
	}

	addrk(nr)
	for rnd := nr - 1; rnd > 0; rnd-- {
		invShift()
		for i := range len(st) {
			st[i] = invSBox[st[i]]
		}
		addrk(rnd)
		for c := range nBlocks {
			a := slices.Clone(st[4*c : 4*c+4])
			st[4*c+0] = mul(a[0], 14) ^ mul(a[1], 11) ^ mul(a[2], 13) ^ mul(a[3], 9)
			st[4*c+1] = mul(a[0], 9) ^ mul(a[1], 14) ^ mul(a[2], 11) ^ mul(a[3], 13)
			st[4*c+2] = mul(a[0], 13) ^ mul(a[1], 9) ^ mul(a[2], 14) ^ mul(a[3], 11)
			st[4*c+3] = mul(a[0], 11) ^ mul(a[1], 13) ^ mul(a[2], 9) ^ mul(a[3], 14)
		}
	}

	invShift()
	for i := range len(st) {
		st[i] = invSBox[st[i]]
	}
	addrk(0)
	return st
}
